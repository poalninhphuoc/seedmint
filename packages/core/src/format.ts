import type { Dataset, Field, FieldKind, OutputFormat, Row, Schema } from "./types.js";

export type { OutputFormat };
export const OUTPUT_FORMATS: OutputFormat[] = ["json", "jsonl", "csv", "sql", "ts", "prisma", "drizzle", "prompt"];

export type SqlDialect = "postgres" | "mysql" | "sqlite" | "mssql";
export const SQL_DIALECTS: SqlDialect[] = ["postgres", "mysql", "sqlite", "mssql"];

export interface RenderMeta {
  locale?: string | string[];
  seed?: number;
  /** SQL output: quoting, types and literals for this database. Without it the output is plain ANSI INSERTs. */
  dialect?: SqlDialect;
  /** SQL output with a dialect: also emit CREATE TABLE (default true). */
  ddl?: boolean;
  /** CSV field separator (default ","). Use ";" where the decimal separator is a comma. */
  delimiter?: string;
  /** CSV: start the file with a UTF-8 byte order mark so Excel reads accents correctly. */
  bom?: boolean;
}

export interface OutFile {
  name: string;
  content: string;
}

const sqlValue = (v: unknown): string => {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "TRUE" : "FALSE";
  const s = typeof v === "object" ? JSON.stringify(v) : String(v);
  return `'${s.replace(/'/g, "''")}'`;
};

const csvCell = (v: unknown, delimiter = ","): string => {
  if (v === null || v === undefined) return "";
  const s = typeof v === "object" ? JSON.stringify(v) : String(v);
  return s.includes(delimiter) || /["\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};

const pascal = (s: string) => s.replace(/(^|[_\-\s]+)(\w)/g, (_, __, c: string) => c.toUpperCase()).replace(/[^A-Za-z0-9]/g, "");
const camel = (s: string) => {
  const p = pascal(s);
  return p.charAt(0).toLowerCase() + p.slice(1);
};
const key = (k: string) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k));

function tsType(schema: Schema, table: string): string {
  const t = schema.tables.find((x) => x.name === table);
  const lines = (t?.fields ?? []).map((f) => {
    const base = f.kind === "integer" || f.kind === "number" ? "number" : f.kind === "boolean" ? "boolean" : f.kind === "json" ? "unknown" : "string";
    return `  ${key(f.name)}: ${base}${f.optional ? " | null" : ""};`;
  });
  return `export interface ${pascal(table)}Row {\n${lines.join("\n")}\n}`;
}

/** TS literal for rows; date fields become `new Date(...)` so ORMs accept them. */
function tsRows(rows: Row[], fields: Field[] | undefined, indent = "    "): string {
  const dateKeys = new Set((fields ?? []).filter((f) => f.kind === "datetime").map((f) => f.name));
  const lit = (k: string, v: unknown): string =>
    dateKeys.has(k) && typeof v === "string" ? `new Date(${JSON.stringify(v)})` : JSON.stringify(v);
  return rows
    .map((r) => `${indent}{ ${Object.entries(r).map(([k, v]) => `${key(k)}: ${lit(k, v)}`).join(", ")} },`)
    .join("\n");
}

const lowerFirst = (s: string) => s.charAt(0).toLowerCase() + s.slice(1);

function prompt(data: Dataset, schema: Schema | undefined, meta: RenderMeta | undefined): string {
  const locale = [meta?.locale ?? "en"].flat().join(", ");
  const schemaLines = (schema?.tables ?? []).map((t) => {
    const cols = t.fields
      .map((f) => `${f.name}: ${f.kind === "enum" ? (f.enumValues ?? []).map((v) => JSON.stringify(v)).join(" | ") : f.kind}${f.primary ? " (pk)" : ""}${f.ref ? ` -> ${f.ref.table}.${f.ref.field}` : ""}${f.optional ? "?" : ""}`)
      .join(", ");
    return `- **${t.name}**(${cols})`;
  });
  const samples = Object.keys(data).map((t) => {
    const rows = data[t].slice(0, 5);
    return `### ${t} (${rows.length} of ${data[t].length} rows)\n\n\`\`\`json\n${JSON.stringify(rows, null, 2)}\n\`\`\``;
  });
  return [
    "# Mock data for this project",
    "",
    `Generated by seedmint. Locale: ${locale}${meta?.seed !== undefined ? `, seed: ${meta.seed}` : ""}. All values are fake.`,
    "",
    "## Schema",
    "",
    ...schemaLines,
    "",
    "## Sample rows",
    "",
    ...samples.flatMap((s) => [s, ""]),
    "## Instructions for the AI coding agent",
    "",
    "- Use this data as realistic mock data while building the UI. Keep the field names and types exactly as above.",
    "- Do not add fields that are not in the schema. Foreign keys already point at existing rows.",
    "- Show states with null/optional values, long text and non-English characters so the layout is checked against real content.",
    "- Put the data in a mock module (for example `src/mocks/data.ts`) so it can be replaced by the real API later.",
    "",
  ].join("\n");
}

const QUOTE: Record<SqlDialect, (s: string) => string> = {
  postgres: (s) => `"${s.replace(/"/g, '""')}"`,
  sqlite: (s) => `"${s.replace(/"/g, '""')}"`,
  mysql: (s) => `\`${s.replace(/`/g, "``")}\``,
  mssql: (s) => `[${s.replace(/]/g, "]]")}]`,
};

const SQL_TYPES: Record<SqlDialect, Record<FieldKind, string>> = {
  postgres: { string: "TEXT", integer: "INTEGER", number: "DOUBLE PRECISION", boolean: "BOOLEAN", date: "DATE", datetime: "TIMESTAMP", uuid: "UUID", json: "JSONB", enum: "TEXT" },
  mysql: { string: "TEXT", integer: "INT", number: "DOUBLE", boolean: "TINYINT(1)", date: "DATE", datetime: "DATETIME", uuid: "CHAR(36)", json: "JSON", enum: "VARCHAR(64)" },
  sqlite: { string: "TEXT", integer: "INTEGER", number: "REAL", boolean: "INTEGER", date: "TEXT", datetime: "TEXT", uuid: "TEXT", json: "TEXT", enum: "TEXT" },
  mssql: { string: "NVARCHAR(MAX)", integer: "INT", number: "FLOAT", boolean: "BIT", date: "DATE", datetime: "DATETIME2", uuid: "UNIQUEIDENTIFIER", json: "NVARCHAR(MAX)", enum: "NVARCHAR(64)" },
};

/** Types that can be keys must be indexable: MySQL and SQL Server cannot index TEXT / MAX columns. */
function sqlType(d: SqlDialect, f: Field): string {
  const keyed = f.primary || !!f.ref;
  if (keyed && f.kind === "string") return d === "mysql" ? "VARCHAR(191)" : d === "mssql" ? "NVARCHAR(191)" : "TEXT";
  return SQL_TYPES[d][f.kind];
}

function sqlLiteral(d: SqlDialect, v: unknown, kind: FieldKind | undefined): string {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return d === "postgres" ? (v ? "TRUE" : "FALSE") : v ? "1" : "0";
  let s = typeof v === "object" ? JSON.stringify(v) : String(v);
  if ((d === "mysql" || d === "mssql") && (kind === "datetime" || /^\d{4}-\d{2}-\d{2}T[\d:.]+Z$/.test(s))) s = s.replace("T", " ").replace(/Z$/, "");
  if (d === "mysql") s = s.replace(/\\/g, "\\\\");
  const q = `'${s.replace(/'/g, "''")}'`;
  return d === "mssql" ? `N${q}` : q;
}

function renderSql(data: Dataset, schema: Schema | undefined, d: SqlDialect, ddl: boolean): OutFile {
  const q = QUOTE[d];
  const names = Object.keys(data);
  const kinds = (t: string) => new Map((schema?.tables.find((x) => x.name === t)?.fields ?? []).map((f) => [f.name, f.kind]));
  const parts: string[] = [`-- Generated by seedmint for ${d}. Fake data only.`];

  if (ddl && schema) {
    for (const t of schema.tables.filter((x) => names.includes(x.name))) {
      const cols = t.fields.map((f) => `  ${q(f.name)} ${sqlType(d, f)}${f.optional || f.primary ? "" : " NOT NULL"}`);
      const pk = t.fields.filter((f) => f.primary).map((f) => q(f.name));
      if (pk.length) cols.push(`  PRIMARY KEY (${pk.join(", ")})`);
      const done = new Set<string>();
      for (const f of t.fields) {
        if (!f.ref || !names.includes(f.ref.table) || f.ref.table === t.name) continue;
        const key = f.ref.group;
        if (key && done.has(key)) continue;
        const same = key ? t.fields.filter((x) => x.ref?.group === key) : [f];
        if (key) done.add(key);
        cols.push(`  FOREIGN KEY (${same.map((x) => q(x.name)).join(", ")}) REFERENCES ${q(f.ref.table)} (${same.map((x) => q(x.ref!.field)).join(", ")})`);
      }
      const body = `${q(t.name)} (\n${cols.join(",\n")}\n);`;
      parts.push(d === "mssql" ? `IF OBJECT_ID(N'${t.name.replace(/'/g, "''")}', N'U') IS NULL\nCREATE TABLE ${body}` : `CREATE TABLE IF NOT EXISTS ${body}`);
    }
  }

  for (const t of names) {
    const rows = data[t];
    if (!rows.length) continue;
    const cols = Object.keys(rows[0]);
    const k = kinds(t);
    for (let i = 0; i < rows.length; i += 500) {
      const values = rows.slice(i, i + 500).map((r) => `  (${cols.map((c) => sqlLiteral(d, r[c], k.get(c))).join(", ")})`).join(",\n");
      parts.push(`INSERT INTO ${q(t)} (${cols.map(q).join(", ")}) VALUES\n${values};`);
    }
  }
  return { name: `seed.${d}.sql`, content: parts.join("\n\n") + "\n" };
}

export function render(data: Dataset, format: OutputFormat, schema?: Schema, meta?: RenderMeta): OutFile[] {
  const tables = Object.keys(data);
  switch (format) {
    case "json":
      return [{ name: "data.json", content: JSON.stringify(data, null, 2) + "\n" }];
    case "jsonl":
      return [{
        name: "data.jsonl",
        content: tables.flatMap((t) => data[t].map((r: Row) => JSON.stringify({ _table: t, ...r }))).join("\n") + "\n",
      }];
    case "csv":
      return tables.map((t) => {
        const rows = data[t];
        const cols = rows.length ? Object.keys(rows[0]) : schema?.tables.find((x) => x.name === t)?.fields.map((f) => f.name) ?? [];
        const d = meta?.delimiter ?? ",";
        const lines = [cols.map((c) => csvCell(c, d)).join(d), ...rows.map((r) => cols.map((c) => csvCell(r[c], d)).join(d))];
        return { name: `${t}.csv`, content: (meta?.bom ? "\uFEFF" : "") + lines.join("\n") + "\n" };
      });
    case "sql": {
      if (meta?.dialect) return [renderSql(data, schema, meta.dialect, meta.ddl !== false)];
      const out = tables
        .filter((t) => data[t].length)
        .map((t) => {
          const cols = Object.keys(data[t][0]);
          const values = data[t].map((r) => `  (${cols.map((c) => sqlValue(r[c])).join(", ")})`).join(",\n");
          return `INSERT INTO "${t}" (${cols.map((c) => `"${c}"`).join(", ")}) VALUES\n${values};`;
        });
      return [{ name: "seed.sql", content: out.join("\n\n") + "\n" }];
    }
    case "prisma": {
      const blocks = tables
        .filter((t) => data[t].length)
        .map((t) => `  await prisma.${lowerFirst(t)}.createMany({\n    data: [\n${tsRows(data[t], schema?.tables.find((x) => x.name === t)?.fields, "      ")}\n    ],\n  });`);
      const content = `// Generated by seedmint. Fake data only. Run with: npx tsx prisma/seed.ts
import { PrismaClient } from "@prisma/client";

const prisma = new PrismaClient();

async function main() {
${blocks.join("\n\n")}
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
`;
      return [{ name: "seed.ts", content }];
    }
    case "drizzle": {
      const blocks = tables
        .filter((t) => data[t].length)
        .map((t) => `  await db.insert(schema.${t}).values([\n${tsRows(data[t], schema?.tables.find((x) => x.name === t)?.fields, "    ")}\n  ]);`);
      const content = `// Generated by seedmint. Fake data only. Adjust the two imports to your project.
import { db } from "./db";
import * as schema from "./schema";

async function main() {
${blocks.join("\n\n")}
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .then(() => process.exit(0));
`;
      return [{ name: "seed.ts", content }];
    }
    case "prompt":
      return [{ name: "seedmint-prompt.md", content: prompt(data, schema, meta) }];
    case "ts": {
      const blocks = tables.map((t) => {
        const iface = schema ? tsType(schema, t) : "";
        const typeName = schema ? `${pascal(t)}Row[]` : "unknown[]";
        return `${iface}${iface ? "\n\n" : ""}export const ${camel(t)}: ${typeName} = ${JSON.stringify(data[t], null, 2)};`;
      });
      return [{ name: "mock.ts", content: `// Generated by seedmint. Fake data only.\n\n${blocks.join("\n\n")}\n` }];
    }
  }
}
